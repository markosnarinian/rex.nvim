function M.load()
  if vim.g.colors_name then
    vim.cmd("highlight clear")
  end
  -- Palette indices only resolve to the terminal's own colors without
  -- 24-bit color; with termguicolors on, Neovim would ignore them.
  vim.o.termguicolors = false
  vim.g.colors_name = "rex"

  for name, spec in pairs(groups(M.palette)) do
    vim.api.nvim_set_hl(0, name, spec)
  end
end

return M
