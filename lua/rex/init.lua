-- rex.nvim: a colorscheme built from the terminal's own palette.
--
-- Every color is a terminal palette index, never a hex value. Rex themes ship
-- a full 256-color palette tuned to each theme: 16 is the background, 231 the
-- foreground, 232-255 a ramp from background to foreground, and the 6x6x6 cube
-- is tinted toward the background. Using indices lets one colorscheme follow
-- whichever Rex theme is active, dark or light, and follow theme switches live.

local M = {}

-- Palette roles, as terminal color indices.
M.palette = {
  bg = 16, -- theme background
  fg = 231, -- theme foreground
  -- Background-to-foreground ramp.
  bg1 = 233, -- cursor line, floats
  bg2 = 234, -- popup menu, status line
  bg3 = 236, -- selected popup item, tab line
  bg4 = 237, -- visual selection
  line = 239, -- separators, indent guides, whitespace
  dim = 243, -- line numbers, inactive text
  comment = 246,
  subtle = 250, -- punctuation, secondary text
  -- Theme accents.
  red = 1,
  green = 2,
  yellow = 3,
  blue = 4,
  magenta = 5,
  cyan = 6,
  orange = 208,
  -- Tinted backgrounds for diffs and diagnostics.
  add_bg = 22,
  delete_bg = 52,
  change_bg = 17,
  text_bg = 18,
}

